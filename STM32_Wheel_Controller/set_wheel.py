#!/usr/bin/env python3
"""Bake a set_wheel command into the firmware, rebuild and flash it over ST-Link.

    python3 set_wheel.py "set_wheel(0, 0.8, 0)"   # wheel 0, 80 %, forward
    python3 set_wheel.py 0 0.8 0                  # same thing
    python3 set_wheel.py 0 0.5 1 --no-flash       # only rebuild
    python3 set_wheel.py stop                     # all outputs off
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
HEADER = ROOT / "Core" / "Inc" / "wheel_cmd.h"


def parse(argv):
    text = " ".join(argv)
    if text.strip().lower() == "stop":
        return None
    nums = re.findall(r"[-+]?\d*\.?\d+", text)
    if len(nums) != 3:
        sys.exit("usage: set_wheel.py 'set_wheel(0, 0.8, 0)'  (wheel 0..3, duty 0..1, direction 0|1)")
    wheel, duty, direction = float(nums[0]), float(nums[1]), float(nums[2])
    if wheel not in (0, 1, 2, 3):
        sys.exit("wheel must be 0, 1, 2 or 3")
    if not 0.0 <= duty <= 1.0:
        sys.exit("duty must be between 0 and 1")
    if direction not in (0, 1):
        sys.exit("direction must be 0 (forward) or 1 (backward)")
    return int(wheel), duty, int(direction)


def main():
    args = [a for a in sys.argv[1:] if a != "--no-flash"]
    flash = "--no-flash" not in sys.argv[1:]
    if not args:
        sys.exit(__doc__)
    cmd = parse(args)
    enabled, wheel, duty, direction = (0, 0, 0.0, 0) if cmd is None else (1, *cmd)

    HEADER.write_text(
        "/* Generated by set_wheel.py - the command that is applied at startup. */\n"
        f"#define WHEEL_CMD_ENABLED {enabled}\n"
        f"#define WHEEL_CMD_WHEEL {wheel}\n"
        f"#define WHEEL_CMD_DUTY {duty!r}f\n"
        f"#define WHEEL_CMD_DIR {direction}\n"
    )
    print("stop" if cmd is None else f"set_wheel({wheel}, {duty}, {direction})")

    subprocess.check_call(["make", "-C", str(ROOT), "flash" if flash else "all"])


if __name__ == "__main__":
    main()

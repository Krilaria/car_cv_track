#!/usr/bin/env python3
"""Bake one or several set_wheel commands into the firmware, rebuild and flash over ST-Link.
All commands start together after the board resets and run for 3 seconds.

    python3 set_wheel.py "set_wheel(0, 0.8, 0)"          # one wheel
    python3 set_wheel.py 0 0.8 0                         # same thing
    python3 set_wheel.py 0 0.6 1  1 0.6 0  2 0.6 1  3 0.6 0   # four wheels at once
    python3 set_wheel.py "set_wheel(0,0.6,1); set_wheel(1,0.6,0)"
    python3 set_wheel.py 0 0.5 1 --no-flash              # only rebuild
    python3 set_wheel.py stop                            # all outputs off
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
HEADER = ROOT / "Core" / "Inc" / "wheel_cmd.h"


def parse(argv):
    text = " ".join(argv)
    if text.strip().lower() == "stop":
        return []
    nums = re.findall(r"[-+]?\d*\.?\d+", text)
    if not nums or len(nums) % 3:
        sys.exit("usage: set_wheel.py 'set_wheel(0, 0.8, 0)'  or  set_wheel.py 0 0.8 0 1 0.8 0 ...")
    cmds = {}
    for i in range(0, len(nums), 3):
        wheel, duty, direction = float(nums[i]), float(nums[i + 1]), float(nums[i + 2])
        if wheel not in (0, 1, 2, 3):
            sys.exit("wheel must be 0, 1, 2 or 3")
        if not 0.0 <= duty <= 1.0:
            sys.exit("duty must be between 0 and 1")
        if direction not in (0, 1):
            sys.exit("direction must be 0 (forward) or 1 (backward)")
        cmds[int(wheel)] = (int(wheel), duty, int(direction))  # last command per wheel wins
    return list(cmds.values())


def main():
    args = [a for a in sys.argv[1:] if a != "--no-flash"]
    flash = "--no-flash" not in sys.argv[1:]
    if not args:
        sys.exit(__doc__)
    cmds = parse(args)

    items = ", ".join(f"{{{w}, {d!r}f, {r}}}" for w, d, r in cmds) or "{0, 0.0f, 0}"
    HEADER.write_text(
        "/* Generated by set_wheel.py - the commands that are applied at startup. */\n"
        f"#define WHEEL_CMD_COUNT {len(cmds)}\n"
        f"#define WHEEL_CMD_LIST {{ {items} }}\n"
    )
    print("stop" if not cmds else "\n".join(f"set_wheel({w}, {d}, {r})" for w, d, r in cmds))

    subprocess.check_call(["make", "-C", str(ROOT), "flash" if flash else "all"])


if __name__ == "__main__":
    main()
